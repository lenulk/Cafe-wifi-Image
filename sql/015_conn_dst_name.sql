-- ปัญหา: conn_log มีแต่ dst_ip หน้า Admin ค้น "เข้าเว็บไหน" จึงต้องเดาจากคำตอบ DNS ในช่วงเดียวกัน
-- (ผิดได้เมื่อหลายเว็บใช้ IP ร่วมกัน เช่น CDN)
--
-- วิธีแก้: ตอน cafe-logger เขียนแถว conn_log ให้หาชื่อที่ "เครื่องนั้นถาม DNS แล้วได้ IP นี้"
-- ภายใน 1 ชม.ก่อนเริ่ม connection แล้วเก็บไว้ที่ dst_name (ดู logger/conn_collector.py:
-- resolve_dst_names) -- NULL = ไม่รู้ชื่อ (แถวเก่าก่อน migration นี้, เครื่องเข้าด้วย IP ตรง ๆ,
-- ไม่มี DNS ของเครื่องนั้นในช่วงเวลา) ผู้ค้นต้องถือว่า NULL = "ไม่ทราบ" ไม่ใช่ "ไม่มีชื่อ"
--
-- ไม่สร้างดัชนี: ค้นแบบ LIKE '%ชื่อ%' (มี % นำหน้า) ใช้ B-tree ไม่ได้อยู่แล้ว การค้นกรองด้วยช่วง ts
-- (idx_ts) ก่อนเสมอ ส่วนดัชนีเพิ่มจะทำให้ทุก INSERT บน Pi ช้าลงโดยไม่ได้ประโยชน์
--
-- ไม่กระทบ hash chain (logger/integrity.py hash ไฟล์ log ไม่ใช่แถว DB) และ ts/PK/partition เดิม
--
-- 001_schema.sql apply ไปแล้วแก้ตรง ๆ ไม่ได้ จึงเพิ่มผ่าน migration นี้ -- รันซ้ำได้เสมอ
ALTER TABLE conn_log ADD COLUMN IF NOT EXISTS dst_name VARCHAR(255) NULL AFTER dst_ip;
